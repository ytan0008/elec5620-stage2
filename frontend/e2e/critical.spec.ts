import { test, expect } from '@playwright/test'

async function completeOnboarding(page: any) {
  await expect(page.getByRole('heading', { name: "Let's build your learning profile" })).toBeVisible()
  for (const answer of ['IELTS', 'intermediate', '7.0', '2027-12-15', '8', 'writing and speaking']) {
    await page.getByLabel('Your reply').fill(answer)
    await page.getByRole('button', { name: 'Send reply' }).click()
    if (answer !== 'writing and speaking') await expect(page.getByLabel('Your reply')).toHaveValue('')
  }
  await page.getByRole('button', { name: 'Confirm profile and create portrait' }).click()
  await expect(page.getByText(/Starting portrait for a intermediate IELTS learner/)).toBeVisible()
  await page.getByRole('link', { name: 'Go to dashboard' }).click()
}

test('learner practises all four skills, talks to the examiner and starts a mock', async ({ page }) => {
  test.setTimeout(90000)
  const email = `learner${Date.now()}@example.com`
  await page.goto('/')
  await expect(page.getByRole('heading', { name: 'Welcome back' })).toBeVisible()
  await page.getByRole('button', { name: 'Sign up' }).click()
  await page.getByLabel('Full name').fill('Browser Learner')
  await page.getByLabel('Email').fill(email)
  await page.getByLabel('Password').fill('Example123!')
  await page.getByRole('button', { name: 'Create account', exact: true }).click()
  await completeOnboarding(page)
  await expect(page.getByText('Good to see you, Browser.')).toBeVisible()

  await page.getByRole('button', { name: 'Open agent assistant' }).click()
  await expect(page.getByRole('region', { name: 'Learning Coordinator conversation' })).toBeVisible()
  await page.getByRole('textbox', { name: 'Message agent' }).fill('What is my profile goal?')
  await page.getByRole('button', { name: 'Send agent message' }).click()
  await expect(page.getByText(/Your goal is IELTS 7/)).toBeVisible()
  await page.getByRole('button', { name: 'Close agent chat' }).click()

  await page.getByRole('navigation').getByRole('link', { name: 'Learning plan', exact: true }).click()
  await page.getByRole('button', { name: 'Generate first plan' }).click()
  await expect(page.getByText('IELTS starter plan')).toBeVisible()
  await page.getByPlaceholder('Request a change, e.g. more speaking practice').fill('more speaking practice')
  await page.getByRole('button', { name: 'Request changes' }).click()
  await expect(page.getByText('IELTS revised plan')).toBeVisible()
  await page.getByRole('button', { name: 'Accept plan' }).click()
  await expect(page.getByText('Active', { exact: true })).toBeVisible()

  await page.getByRole('navigation').getByRole('link', { name: 'Listening', exact: true }).click()
  await page.getByRole('button', { name: 'Begin' }).click()
  await expect(page.getByRole('region', { name: 'Audio player' })).toBeVisible()
  await page.getByRole('button', { name: 'Submit answers' }).click()
  await expect(page.getByText(/correct/).first()).toBeVisible()

  await page.getByRole('navigation').getByRole('link', { name: 'Question bank', exact: true }).click()
  await page.locator('article').filter({ hasText: 'Working from home' }).getByRole('button', { name: 'Start practice' }).click()
  await page.getByLabel('Essay editor').fill('Working from home saves commuting time. For example, a consultant can use that extra hour to give more thoughtful advice to clients. However, clear communication routines are needed to support teamwork.')
  await page.getByRole('button', { name: /Submit for feedback/ }).click()
  await expect(page.getByText('Verified feedback')).toBeVisible()

  await page.getByRole('navigation').getByRole('link', { name: 'Speaking', exact: true }).click()
  await page.getByRole('button', { name: 'Start speaking test' }).click()
  await expect(page.getByText(/I'll be your examiner today/)).toBeVisible()
  await page.getByLabel('Type your answer').fill('My name is Browser Learner.')
  await page.getByRole('button', { name: 'Send', exact: true }).click()
  await expect(page.getByText(/in this first part/)).toBeVisible()

  await expect(page.getByRole('navigation').getByRole('link', { name: 'Agent activity', exact: true })).toHaveCount(0)
  await page.getByRole('navigation').getByRole('link', { name: 'Mock examination', exact: true }).click()
  await page.getByRole('button', { name: /Start short mock/ }).click()
  await expect(page.getByText('Unofficial computer-delivered practice')).toBeVisible()
  await expect(page.getByRole('button', { name: 'Open agent assistant' })).toHaveCount(0)
  // IELTS test day: the written test runs section by section; speaking is a separate session the same day.
  await expect(page.getByRole('heading', { name: 'Speaking test' })).toBeVisible()
  await page.getByRole('button', { name: /Start written test/ }).click()
  await page.getByLabel('Answer 1', { exact: true }).fill('Kowalski')
  await page.getByRole('button', { name: /Finish Listening/ }).click()
  await page.getByRole('alertdialog').getByRole('button', { name: /Finish Listening/ }).click()
  await expect(page.locator('article').first()).toBeVisible()
})

